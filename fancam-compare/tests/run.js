const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const out = process.argv[2];
  const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const page = await browser.newPage({ viewport: { width: 400, height: 900 }, acceptDownloads: true });
  page.on('console', (m) => console.log('[console]', m.type(), m.text()));
  page.on('pageerror', (e) => console.log('[pageerror]', e.message));
  await page.goto('http://127.0.0.1:8765/index.html');
  console.log('canPlay mp4:', await page.evaluate(() => document.createElement('video').canPlayType('video/mp4; codecs="avc1.4D401E"')));
  console.log('recorder mp4:', await page.evaluate(() => MediaRecorder.isTypeSupported('video/mp4')));
  await page.screenshot({ path: path.join(out, '0_empty.png') });
  const t0 = Date.now();
  await page.click('#sampleBtn');
  await page.waitForFunction(() => window.__dance.aligned, null, { timeout: 60000 });
  console.log('align took', Date.now() - t0, 'ms');
  const r = await page.evaluate(() => ({ d: window.__dance.d, L: window.__dance.L, status: document.getElementById('statusMain').textContent + ' | ' + document.getElementById('statusSub').textContent }));
  console.log(JSON.stringify(r));
  await page.waitForTimeout(800);
  await page.screenshot({ path: path.join(out, '1_aligned.png'), fullPage: true });
  const dlP = page.waitForEvent('download', { timeout: 120000 });
  await page.click('#exportBtn');
  await page.waitForFunction(() => !document.getElementById('result').hidden, null, { timeout: 120000 });
  await page.screenshot({ path: path.join(out, '2_done.png'), fullPage: true });
  await page.click('#saveBtn');
  const dl = await dlP;
  const f = path.join(out, 'out_' + dl.suggestedFilename());
  await dl.saveAs(f);
  console.log('saved', f);
  await browser.close();
})();
